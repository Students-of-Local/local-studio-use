// `local-studio-browser pi-extension` writes local-studio.ts for pi and touches nothing else in the folder.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { loadTs } from "./helpers/bundle-ts.mjs";

const { writePiExtension } = await loadTs(`export { writePiExtension } from "@src/pi-extension.ts";`);

const root = mkdtempSync(join(process.env.TMPDIR || tmpdir(), "local-studio-pi-"));
after(() => rmSync(root, { recursive: true, force: true }));

const dir = (name) => {
	const d = join(root, name);
	mkdirSync(d, { recursive: true });
	return d;
};

test("writes local-studio.ts with the tools, and nothing else in an empty folder", () => {
	const d = dir("fresh");
	const file = writePiExtension(d);
	assert.equal(file, join(d, "local-studio.ts"));
	assert.deepEqual(readdirSync(d), ["local-studio.ts"]);
	const text = readFileSync(file, "utf8");
	assert.match(text, /^\/\/ Generated by `[^`]+ pi-extension`/);
	assert.match(text, /export default function localStudioExtension\(pi: ExtensionAPI\)/);
	assert.match(text, /name: "browser_navigate"/);
});

test("a second run writes its own file again and leaves the others in the folder alone", () => {
	const d = dir("again");
	writeFileSync(join(d, "mine.ts"), "// my own pi extension\n");
	writePiExtension(d);
	writePiExtension(d);
	assert.deepEqual(readdirSync(d).sort(), ["local-studio.ts", "mine.ts"]);
	assert.equal(readFileSync(join(d, "mine.ts"), "utf8"), "// my own pi extension\n");
});
