#!/usr/bin/env node
// Writes cli/src/relay-dist.ts from a baney75/local-studio-tunnels checkout: the relay Worker bundle (relay/dist/relay.js) and its
// deploy config (relay/dist/wrangler.jsonc), as the strings `remote setup` deploys to the person's own Cloudflare account.
// Usage: node scripts/vendor-relay.mjs <local-studio-tunnels checkout>. Then update the digests in cli/test/relay-vendor.test.mjs.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const checkout = process.argv[2];
if (!checkout) {
	console.error("Usage: node scripts/vendor-relay.mjs <local-studio-tunnels checkout>");
	process.exit(2);
}
const commit = execFileSync("git", ["-C", checkout, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
// The stamped commit must hold the bytes it names.
if (execFileSync("git", ["-C", checkout, "status", "--porcelain", "--", "relay"], { encoding: "utf8" })) {
	console.error(`${checkout} has uncommitted changes under relay/.`);
	process.exit(1);
}
const read = (name) => readFileSync(join(checkout, "relay", "dist", name), "utf8");
// A template literal keeps the file readable line by line; only backslashes, backticks and "${" need escaping.
const literal = (text) => `\`${text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
const out = `// Generated by scripts/vendor-relay.mjs from baney75/local-studio-tunnels relay/dist at commit
// ${commit}. Do not edit: run the script again. Both repositories are baney75's;
// this copy is distributed under Local Studio's license (AGPL-3.0). cli/test/relay-vendor.test.mjs pins each file's SHA-256.

/** The upstream commit these files came from. */
export const RELAY_COMMIT = "${commit}";

/** relay/dist/relay.js: the whole relay Worker in one file. */
export const RELAY_JS = ${literal(read("relay.js"))};

/** relay/dist/wrangler.jsonc: its deploy config. \`--name\` on the deploy command sets the Worker's name. */
export const RELAY_WRANGLER = ${literal(read("wrangler.jsonc"))};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "cli", "src", "relay-dist.ts");
writeFileSync(target, out);
console.log(`Wrote ${target} from ${commit}`);
